/* Beam Analyzer — final internal-hinge visual cleanup.
 * An internal hinge is a release, not a support symbol:
 * draw only an open circle intersecting the beam.
 */
(function(){
  'use strict';
  const $=s=>document.querySelector(s);
  const n=v=>Number(v);
  const isHinge=s=>s&&s.type==='internal-hinge';
  let observer=null;
  let drawing=false;

  function draw(){
    if(drawing)return;
    const canvas=$('#beamCanvas'),svg=canvas?.querySelector('svg');
    if(!svg||typeof model==='undefined'||!Array.isArray(model.supports))return;

    drawing=true;
    if(observer)observer.disconnect();
    try{
      svg.querySelectorAll('.internalHingeGraphic,.baCanonicalHinge,.baCanonicalHingeV3').forEach(e=>e.remove());

      const beam=svg.querySelector('.beamLine');
      if(!beam)return;
      const bx1=n(beam.getAttribute('x1')),bx2=n(beam.getAttribute('x2')),by=n(beam.getAttribute('y1'));
      const total=Math.max(typeof len==='function'?n(len()):1,1);
      const xFor=p=>bx1+Math.max(0,Math.min(total,n(p)))/total*(bx2-bx1);
      const NS='http://www.w3.org/2000/svg';
      const hinges=model.supports.filter(isHinge);

      hinges.forEach((s,hi)=>{
        const id=String(s.id);

        // Remove the actual pin/roller/fixed group generated by app.js.
        svg.querySelectorAll('g.supportDrag[data-id]').forEach(g=>{
          if(String(g.getAttribute('data-id'))===id)g.remove();
        });

        // The dimension renderer labels every support S1/S2/S3...
        // Rename the hinge's dimension marker so it is not presented as a pin.
        const supportIndex=model.supports.indexOf(s)+1;
        svg.querySelectorAll('text').forEach(t=>{
          const txt=(t.textContent||'').trim();
          if(txt===`S${supportIndex}`)t.textContent=`H${hi+1}`;
          else if(txt.startsWith(`S${supportIndex}:`))t.textContent=txt.replace(`S${supportIndex}:`,`H${hi+1}:`);
        });

        const x=xFor(s.position);
        const g=document.createElementNS(NS,'g');
        g.setAttribute('class','baCanonicalHingeV3');
        g.setAttribute('pointer-events','none');

        const circle=document.createElementNS(NS,'circle');
        circle.setAttribute('cx',String(x));
        circle.setAttribute('cy',String(by));
        circle.setAttribute('r','8.5');
        circle.setAttribute('fill','var(--card,#fff)');
        circle.setAttribute('stroke','var(--text,#20252b)');
        circle.setAttribute('stroke-width','2');
        circle.setAttribute('vector-effect','non-scaling-stroke');
        g.appendChild(circle);

        const name=document.createElementNS(NS,'text');
        name.setAttribute('x',String(x));
        name.setAttribute('y',String(by+45));
        name.setAttribute('text-anchor','middle');
        name.setAttribute('fill','var(--text,#20252b)');
        name.setAttribute('font-size','12');
        name.setAttribute('font-weight','600');
        name.textContent=`H${hi+1} (Internal Hinge)`;
        g.appendChild(name);

        const pos=document.createElementNS(NS,'text');
        pos.setAttribute('x',String(x));
        pos.setAttribute('y',String(by+62));
        pos.setAttribute('text-anchor','middle');
        pos.setAttribute('fill','var(--muted,#6b7280)');
        pos.setAttribute('font-size','10');
        pos.textContent=`@ ${typeof fmt==='function'?fmt(s.position):s.position} ${typeof unitText==='function'?unitText('length'):''}`;
        g.appendChild(pos);

        svg.appendChild(g);
      });
    }finally{
      drawing=false;
      if(observer)observer.observe(canvas,{childList:true,subtree:true});
    }
  }

  function install(){
    const canvas=$('#beamCanvas');
    if(!canvas)return;
    if(!observer){
      observer=new MutationObserver(()=>requestAnimationFrame(draw));
      observer.observe(canvas,{childList:true,subtree:true});
    }
    const base=window.renderBeam;
    if(typeof base==='function'&&!base.__internalHingeVisualV3){
      function wrapped(){base();requestAnimationFrame(draw)}
      wrapped.__internalHingeVisualV3=true;
      window.renderBeam=wrapped;
    }
    requestAnimationFrame(draw);
  }

  install();
  setTimeout(install,0);
  setTimeout(install,100);
  setTimeout(install,500);
})();
