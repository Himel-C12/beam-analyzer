/* Beam Analyzer — internal hinge renderer v3.
   Reads the live support rows, so the visual state follows the dropdown immediately.
   Removes the normal Pin/Roller graphic for hinge rows and draws an open-circle hinge.
*/
(function(){
  'use strict';
  const $$=s=>[...document.querySelectorAll(s)];
  const n=v=>Number(v);
  const NS='http://www.w3.org/2000/svg';

  function supportRows(){
    const out=[];
    $$('#supportRows tr').forEach((tr,i)=>{
      const sel=tr.querySelector('select[data-k="type"]');
      const pos=tr.querySelector('input[data-k="position"]');
      if(sel&&pos) out.push({id:String(sel.dataset.sup||i+1),type:sel.value,position:n(pos.value)});
    });
    return out;
  }

  function render(){
    const svg=document.querySelector('#beamCanvas svg');
    if(!svg)return;
    svg.querySelectorAll('.baUiInternalHinge').forEach(e=>e.remove());

    const beam=svg.querySelector('.beamLine');
    if(!beam)return;
    const x1=n(beam.getAttribute('x1')),x2=n(beam.getAttribute('x2')),y=n(beam.getAttribute('y1'));
    const rows=supportRows();
    const total=Math.max(...rows.map(s=>s.position),1);

    rows.forEach((s,index)=>{
      if(s.type!=='internal-hinge')return;

      // Remove the ordinary support graphic generated by the base renderer.
      svg.querySelectorAll('g.supportDrag').forEach(g=>{
        if(String(g.getAttribute('data-id'))===s.id) g.remove();
      });

      const x=x1+(Math.max(0,Math.min(total,s.position))/total)*(x2-x1);
      const g=document.createElementNS(NS,'g');
      g.setAttribute('class','baUiInternalHinge');
      g.setAttribute('pointer-events','none');

      const c=document.createElementNS(NS,'circle');
      c.setAttribute('cx',x);c.setAttribute('cy',y);c.setAttribute('r','9');
      c.setAttribute('fill','var(--card,#fff)');
      c.setAttribute('stroke','var(--text,#20252b)');
      c.setAttribute('stroke-width','2');
      c.setAttribute('vector-effect','non-scaling-stroke');
      g.appendChild(c);

      const label=document.createElementNS(NS,'text');
      label.setAttribute('x',x);label.setAttribute('y',y+45);
      label.setAttribute('text-anchor','middle');
      label.setAttribute('fill','var(--text,#20252b)');
      label.setAttribute('font-size','12');label.setAttribute('font-weight','600');
      label.textContent=`H${index+1} (Internal Hinge)`;
      g.appendChild(label);

      const pos=document.createElementNS(NS,'text');
      pos.setAttribute('x',x);pos.setAttribute('y',y+62);
      pos.setAttribute('text-anchor','middle');
      pos.setAttribute('fill','var(--muted,#6b7280)');pos.setAttribute('font-size','10');
      pos.textContent=`@ ${Number.isFinite(s.position)?s.position:0} m`;
      g.appendChild(pos);

      svg.appendChild(g);
    });
  }

  function install(){
    render();
    const rows=document.querySelector('#supportRows');
    if(rows&&!rows.__hingeRendererV3){
      rows.addEventListener('change',()=>requestAnimationFrame(render));
      rows.addEventListener('input',()=>requestAnimationFrame(render));
      new MutationObserver(()=>requestAnimationFrame(render)).observe(rows,{childList:true,subtree:true});
      rows.__hingeRendererV3=true;
    }
    const canvas=document.querySelector('#beamCanvas');
    if(canvas&&!canvas.__hingeCanvasRendererV3){
      new MutationObserver(()=>requestAnimationFrame(render)).observe(canvas,{childList:true,subtree:true});
      canvas.__hingeCanvasRendererV3=true;
    }
  }

  install();
  setTimeout(install,100);
  setTimeout(install,500);
  setTimeout(install,1200);
})();