/* Beam Analyzer — internal hinge UI fix.
 * Keeps internal hinges as a real support-row type and renders them as an
 * open circle instead of silently falling back to a roller.
 */
(function(){
  'use strict';
  const $=s=>document.querySelector(s);
  const $$=s=>[...document.querySelectorAll(s)];
  const n=v=>Number(v);
  const NS='http://www.w3.org/2000/svg';

  function supportData(){
    const out=new Map();
    $$('#supportRows tr').forEach(tr=>{
      const sel=tr.querySelector('select[data-sup][data-k="type"]');
      const pos=tr.querySelector('input[data-sup][data-k="position"]');
      if(!sel||!pos)return;
      const id=sel.dataset.sup;
      out.set(String(id),{type:sel.value,position:n(pos.value)});
    });
    return out;
  }

  function ensureOption(){
    $$('#supportRows select[data-k="type"]').forEach(sel=>{
      if(!sel.querySelector('option[value="internal-hinge"]')){
        const o=document.createElement('option');
        o.value='internal-hinge';
        o.textContent='Internal Hinge';
        sel.appendChild(o);
      }
    });
  }

  function renderHinges(){
    const canvas=$('#beamCanvas'),svg=canvas?.querySelector('svg');
    if(!svg)return;
    const data=supportData();

    svg.querySelectorAll('.baUiInternalHinge').forEach(e=>e.remove());

    const beam=svg.querySelector('.beamLine');
    if(!beam)return;
    const bx1=n(beam.getAttribute('x1')),bx2=n(beam.getAttribute('x2')),by=n(beam.getAttribute('y1'));
    const total=[...data.values()].reduce((m,s)=>Math.max(m,s.position),0) || 1;
    const dim=svg.querySelector('.dimLine');
    const W=1200,pad=72;
    const beamLength=bx2-bx1;
    const xFor=p=>bx1+Math.max(0,Math.min(1,p/(Math.max(total,1))))*beamLength;

    data.forEach((s,id)=>{
      if(s.type!=='internal-hinge')return;
      const old=svg.querySelector(`g.supportDrag[data-id="${CSS.escape(id)}"]`);
      const x=xFor(s.position);

      // Remove the normal Pin/Roller support symbol generated by app.js.
      if(old)old.remove();

      const g=document.createElementNS(NS,'g');
      g.setAttribute('class','baUiInternalHinge');
      g.setAttribute('pointer-events','none');

      const circle=document.createElementNS(NS,'circle');
      circle.setAttribute('cx',x);circle.setAttribute('cy',by);circle.setAttribute('r','9');
      circle.setAttribute('fill','var(--card,#fff)');
      circle.setAttribute('stroke','var(--text,#20252b)');
      circle.setAttribute('stroke-width','2');
      circle.setAttribute('vector-effect','non-scaling-stroke');
      g.appendChild(circle);

      const label=document.createElementNS(NS,'text');
      label.setAttribute('x',x);label.setAttribute('y',by+45);
      label.setAttribute('text-anchor','middle');
      label.setAttribute('fill','var(--text,#20252b)');
      label.setAttribute('font-size','12');label.setAttribute('font-weight','600');
      label.textContent='H1 (Internal Hinge)';
      g.appendChild(label);

      const pos=document.createElementNS(NS,'text');
      pos.setAttribute('x',x);pos.setAttribute('y',by+62);
      pos.setAttribute('text-anchor','middle');
      pos.setAttribute('fill','var(--muted,#6b7280)');pos.setAttribute('font-size','10');
      pos.textContent=`@ ${Number.isFinite(s.position)?s.position:0} m`;
      g.appendChild(pos);
      svg.appendChild(g);
    });

    // Correct the dimension labels for hinge rows: they are joints, not
    // conventional supports, so show H1 instead of S3/Sn.
    const hingeIds=new Set([...data].filter(([,s])=>s.type==='internal-hinge').map(([id])=>id));
    svg.querySelectorAll('text.dimText').forEach(t=>{
      const m=t.textContent.match(/^S(\d+):/);
      if(!m)return;
      const idx=Number(m[1])-1;
      const rows=$$('#supportRows tr');
      const sel=rows[idx]?.querySelector('select[data-k="type"]');
      if(sel?.value==='internal-hinge')t.textContent=t.textContent.replace(/^S\d+:/,'H1:');
    });
  }

  function install(){
    ensureOption();
    renderHinges();
    const canvas=$('#beamCanvas');
    if(canvas&&!canvas.__hingeUiFix){
      const observer=new MutationObserver(()=>{
        ensureOption();
        requestAnimationFrame(renderHinges);
      });
      observer.observe(canvas,{childList:true,subtree:true});
      canvas.__hingeUiFix=observer;
    }
    const rows=$('#supportRows');
    if(rows&&!rows.__hingeUiRowsFix){
      const observer=new MutationObserver(()=>ensureOption());
      observer.observe(rows,{childList:true,subtree:true});
      rows.__hingeUiRowsFix=observer;
    }
  }

  install();
  setTimeout(install,50);
  setTimeout(install,250);
  setTimeout(install,750);
})();
